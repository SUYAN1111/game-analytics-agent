 assert.ok(j.evidence.filter(e=>e.kind==='claims').every(e=>e.fact.scope.version_id==='V6'));
 assert.equal((await session()).id,sid);checks.push('persisted clarification choice, no auto-submit, real V6 query');
 await send('那前一次更新呢？');j=await done();assert.deepEqual(j.routing.plan.versions,['V5']);
 assert.ok(j.evidence.filter(e=>e.kind==='claims').every(e=>e.fact.scope.version_id==='V5'));
