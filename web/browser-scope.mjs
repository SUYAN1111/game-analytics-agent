 checks.push('partial completion contains actual comparison evidence and exports limits');
 await fresh();await send('查看前一次更新的玩家分组');j=await done();assert.equal(j.routing.plan.snapshot,'replay_V5main');
 await send('那第二组呢？');j=await done();assert.equal(j.routing.plan.group,'G02');
 assert.ok(j.evidence.every(e=>e.fact.selection.scope.segment_id==='G02'&&e.fact.selection.scope.snapshot_id==='replay_V5main'));
